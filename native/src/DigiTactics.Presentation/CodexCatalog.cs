    CodexAugment[] Augments,CodexWisp[] Wisps,CodexRule[] Rules,string[] ComponentIds,string[][] RecipeGrid,string[] TraitKinds,string[] Tabs);

/// <summary>Display data generated by the original Codex for each set and pace.</summary>
public sealed class CodexCatalog
{
    private sealed record Document(int Schema,CodexVariant[] Variants);
    private readonly Dictionary<string,CodexVariant> variants;
    public IReadOnlyCollection<CodexVariant> Variants=>variants.Values;
    public CodexCatalog(string path)
    {
        var data=JsonSerializer.Deserialize<Document>(File.ReadAllBytes(path),new JsonSerializerOptions{PropertyNameCaseInsensitive=true})
            ??throw new InvalidDataException("Missing Codex catalog.");
        if(data.Schema!=1||data.Variants is not {Length:>0})throw new InvalidDataException("Unsupported or empty Codex catalog.");
        variants=new(StringComparer.Ordinal);
        foreach(var variant in data.Variants)
        {
            if(!variants.TryAdd(variant.Id,variant))throw new InvalidDataException("Duplicate Codex variant: "+variant.Id);
            if(variant.RecipeGrid.Length!=variant.ComponentIds.Length||variant.RecipeGrid.Any(row=>row.Length!=variant.ComponentIds.Length)
                ||variant.Rules.Any(rule=>rule.Blocks.Length==0||rule.Blocks.Any(block=>block.Kind is not ("paragraph" or "table")))
                ||variant.Lines.Any(line=>line.Forms.Length==0)||variant.Traits.Select(trait=>trait.Id).Distinct().Count()!=variant.Traits.Length)
                throw new InvalidDataException("Incomplete Codex variant: "+variant.Id);
        }
    }
    public CodexVariant Variant(string id)=>variants.TryGetValue(id,out var variant)?variant:throw new InvalidDataException("Missing Codex variant: "+id);
    /// <summary>Original Codex search: every whitespace-separated word must appear, without case sensitivity.</summary>
    public static bool Matches(string? query,string searchText)=>string.IsNullOrWhiteSpace(query)
        ||query.Split((char[]?)null,StringSplitOptions.RemoveEmptyEntries).All(word=>searchText.Contains(word,StringComparison.OrdinalIgnoreCase));
}
