// Translate the deliberately small numeric Canvas dialect in mystery-content.js.
// JavaScript remains a build dependency only; native draws the generated C# directly.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'../..');
const source=fs.readFileSync(path.join(root,'js/mystery-content.js'),'utf8').replace(/\r\n/g,'\n');
const begin='// BEGIN NATIVE MYSTERY FINALES',end='// END NATIVE MYSTERY FINALES';
if(source.split(begin).length!==2||source.split(end).length!==2)throw Error('Expected one authored finale block');
const body=source.slice(source.indexOf(begin)+begin.length,source.indexOf(end));
const signatures={
 finaleOval:'EliminationCanvas c,double x,double y,double rx,double ry,double rot,string col,double alpha',
 finaleLine:'EliminationCanvas c,double[] points,string col,double alpha,double width',
 finalePoly:'EliminationCanvas c,double[] points,string col,double alpha',
 finaleStar:'EliminationCanvas c,double x,double y,double r,double rot,string col,double alpha',
 finaleHex:'EliminationCanvas c,double x,double y,double r,string col,double alpha',
 finaleWave:'EliminationCanvas c,double w,double h,double t,double baseline,double amp,string col,double alpha',
 finaleDraw:'EliminationCanvas c,double w,double h,double t,int pool,int index,string color'
};
// Reject unsupported syntax/calls instead of silently changing their meaning.
const token=/\s+|\/\/[^\r\n]*|'[^'\\\r\n]*'|(?:\d+\.?\d*|\.\d+)|[A-Za-z_]\w*|===|!==|<=|>=|\+\+|--|\+=|-=|[{}()[\],;:.?=+*/%<>!-]/y;
const tokens=[];
for(let at=0;at<body.length;){token.lastIndex=at;const match=token.exec(body);if(!match)throw Error('Unsupported finale syntax near '+body.slice(at,at+50));at=token.lastIndex;tokens.push(match[0]);}
const calls=new Set([...Object.keys(signatures),'if','for','switch']);
const members=new Set(['sin','cos','min','max','abs','PI','length','fillStyle','strokeStyle','globalAlpha','lineWidth','beginPath','closePath','moveTo','lineTo','ellipse','fill','stroke','save','restore','fillRect','createLinearGradient','addColorStop']);
const significant=tokens.filter(t=>!/^\s|^\/\//.test(t));
for(let i=0;i<significant.length;i++){
 const value=significant[i];
 if(significant[i-1]==='.'&&!members.has(value))throw Error('Unsupported finale member '+value);
 if(/^[A-Za-z_]\w*$/.test(value)&&significant[i+1]==='('&&significant[i-1]!=='.'&&!calls.has(value))throw Error('Unsupported finale call '+value);
 if(['while','do','return','new','var','async','await','throw','try','catch'].includes(value))throw Error('Unsupported finale construct '+value);
}
let result=body.replace(/function (\w+)\(([^)]*)\)/g,(_,name,args)=>{
 if(!signatures[name])throw Error('Unknown finale helper '+name);
 const expected=signatures[name].split(',').map(s=>s.trim().split(' ').at(-1).replace('baseline','base'));
 if(args!==expected.join(','))throw Error('Finale signature changed: '+name);
 return `${name==='finaleDraw'?'internal':'private'} static void ${name}(${signatures[name]})`;
});
if((result.match(/static void /g)||[]).length!==Object.keys(signatures).length)throw Error('Finale helper count changed');
result=result.replace(/\/\/[^\r\n]*|'[^'\\\r\n]*'|\bconst\b|\blet\b|\bbase\b|===|!==|Math\.(sin|cos|min|max|abs)|\.length|,\[([^\[\]]*)\]/g,(value,...parts)=>{
 if(value.startsWith('//'))return value;
 if(value.startsWith("'"))return JSON.stringify(value.slice(1,-1));
 if(value==='const')return 'var';
 if(value==='let')return 'int';
 if(value==='base')return 'baseline';
 if(value==='===')return '==';
 if(value==='!==')return '!=';
 if(value==='.length')return '.Length';
 if(value.startsWith('Math.'))return 'Math.'+parts[0][0].toUpperCase()+parts[0].slice(1);
 // Array literals contain numeric expressions only. Their contents need math translation too.
 return ',new double[]{'+parts[1].replace(/Math\.(sin|cos|min|max|abs)/g,(_,name)=>'Math.'+name[0].toUpperCase()+name.slice(1)).replace(/\bbase\b/g,'baseline')+'}';
});
const output='// <auto-generated />\n// Source: js/mystery-content.js; regenerate with tools/export-mystery-kill-themes.cjs.\n'+
 '// Authored block SHA-256: '+crypto.createHash('sha256').update(body).digest('hex')+'\n'+
 'namespace DigiTactics.Presentation;\n\ninternal static class MysteryEliminationThemes\n{\n'+result.trimEnd()+'\n}\n';
const destination=path.join(root,'native/src/DigiTactics.Presentation/MysteryEliminationThemes.g.cs');
if(process.argv.includes('--check')){
 if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8').replace(/\r\n/g,'\n')!==output)throw Error('Native mystery finale source is stale; run export-mystery-kill-themes.cjs');
 console.log('Native mystery finale source matches the 40 authored compositions.');
}else{fs.writeFileSync(destination,output);console.log('Generated native mystery finale geometry from the 40 authored compositions.');}
