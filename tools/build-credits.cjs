// Build a file-based attribution inventory. Source-page contributors are verified separately.
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const write = (f, value) => fs.writeFileSync(path.join(root, f), value);
const code = read('js/models.js'), ctx = {};
vm.createContext(ctx); vm.runInContext(code, ctx);
const original = {};
vm.createContext(original); vm.runInContext(code.split('// RIPS-START')[0] + '})(this);', original);
const sources = { ...original.DT.MODEL_SOURCES, ...ctx.DT.MODEL_SOURCES };
const index = JSON.parse(read('models/index.json'));
const rows = new Map();
function add(file, source, key) {
  if (!fs.existsSync(path.join(root, file))) return;
  let row = rows.get(file);
  if (!row) rows.set(file, row = { file, keys: [], name: source?.name || path.basename(file), url: source?.url || null,
    author: source?.author || null, license: source?.license || 'Not recorded', role: source?.rip || file.includes('/rip_') ? 'Game asset / community extraction' : 'Model upload' });
  if (key && !row.keys.includes(key)) row.keys.push(key);
  if (!row.url && source?.url) Object.assign(row, { name: source.name, url: source.url, author: source.author, license: source.license });
}
for (const [key, file] of Object.entries(index)) add(file, sources[key], key);
for (const source of [...Object.values(original.DT.MODEL_SOURCES), ...Object.values(ctx.DT.MODEL_SOURCES)]) {
  if (!source.uid) continue;
  const file = 'models/files/' + source.uid.replace(/^rip-/, 'rip_') + '.glb';
  add(file, source);
}
const legends = read('js/legends.js');
// A shipped file retained from conversion is not referenced by a current roster key.
add('models/files/rip_l_arresterdramon.glb', { name: 'Arresterdramon (Digimon Links)', url: 'https://models.spriters-resource.com/mobile/digimonlinks/asset/324496/', author: 'The Models Resource', license: 'Game rip', rip: true });
const extract = name => legends.match(new RegExp('const ' + name + ' = (\\[[\\s\\S]*?\\n\\]);'))[1];
const lc = { RA: 'https://models.spriters-resource.com/mobile/digimonrearise/asset/', REARISE: 'Digimon ReArise', swapDance: () => [] };
vm.createContext(lc);
for (const r of vm.runInContext(extract('LIST'), lc)) add(`models/legends/${r[0]}.glb`, { name: r[1] + ' (Digimon Links)', url: `https://models.spriters-resource.com/mobile/digimonlinks/asset/${r[4]}/`, author: 'The Models Resource', license: 'Game rip', rip: true }, 'legend:' + r[0]);
for (const r of vm.runInContext(extract('LIST2'), lc)) add(`models/legends/${r[0]}.glb`, { name: `${r[1]} (${r[5]})`, url: r[4], author: 'The Models Resource', license: 'Game rip', rip: true }, 'legend:' + r[0]);
for (const folder of ['models/files', 'models/legends']) for (const name of fs.readdirSync(path.join(root, folder))) if (name.endsWith('.glb')) add(folder + '/' + name);
const verifiedPath = path.join(root, 'docs/credits/contributors.json');
const verified = fs.existsSync(verifiedPath) ? JSON.parse(fs.readFileSync(verifiedPath, 'utf8')) : {};
for (const r of rows.values()) {
  const v = verified[r.url];
  r.contributors = v?.contributors || (r.author && r.author !== 'The Models Resource' ? [r.author] : []);
  r.attributionStatus = r.contributors.length ? (v ? 'Source page verified' : 'Recorded upload credit') : 'Contributor not yet verified';
  r.permissionStatus = r.license === 'Game rip' || r.role.startsWith('Game asset') ? 'Redistribution permission not established' : 'Verify source license and underlying rights';
}
const assets = [...rows.values()].sort((a,b) => a.name.localeCompare(b.name));
write('docs/credits/model-assets.json', JSON.stringify({ generatedFrom: ['models/index.json', 'js/models.js', 'js/legends.js'], assets }, null, 2) + '\n');
const groups = new Map();
for (const r of assets) {
  const key = r.url || r.file;
  if (!groups.has(key)) groups.set(key, { name: r.name, url: r.url, contributors: r.contributors, license: r.license, files: [], status: r.attributionStatus });
  groups.get(key).files.push(r.file);
}
const entries = [...groups.values()];
write('js/credits-data.js', '// Generated by tools/build-credits.cjs. Names credit uploaders/extractors, not automatically original modelers.\nwindow.DT = window.DT || {};\nwindow.DT.AssetCredits = ' + JSON.stringify(entries) + ';\n');
const cell = s => String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
write('docs/credits/MODELS.md', '# Model source credits\n\nGenerated from the actual bundled GLB files. Uploaders and extractors are credited for their documented contributions; they are not assumed to be the original modelers or rights holders. “Game rip” is a provenance label, not a redistribution license. Unknown contributors remain explicitly marked. Full file/key mappings: [model-assets.json](model-assets.json).\n\n| Asset / source | Contributor(s) | Recorded label | Files |\n| --- | --- | --- | --- |\n' + entries.map(r => `| ${r.url ? '[' + cell(r.name) + '](' + r.url + ')' : cell(r.name)} | ${cell(r.contributors.join(', ') || 'Not yet verified')} | ${cell(r.license)} | ${r.files.map(f => '`' + f + '`').join('<br>')} |`).join('\n') + '\n');
console.log(JSON.stringify({ files: assets.length, sources: entries.length, missingSource: assets.filter(a=>!a.url).length, missingContributor: assets.filter(a=>!a.contributors.length).length }));
